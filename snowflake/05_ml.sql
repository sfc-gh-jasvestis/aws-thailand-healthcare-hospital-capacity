-- Capacity overflow risk scoring and admissions forecast over the synthetic snapshot.
-- Predicts P(confirmed capacity overflow in the next 7 days) per ward
-- and reports out-of-time holdout metrics; nothing is seeded as a prediction.
-- These are operational bed-flow scores, not diagnostic or clinical predictions.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.OVERFLOW_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, s.CATEGORY, s.SERVICE_TIER, s.NURSE_FTE,
       r.BOARDING_HOURS, r.AWAITING_BED,
       AVG(r.BOARDING_HOURS) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS BOARDING_7D,
       SUM(r.OVERFLOW_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS OVERFLOW_30D,
       IFF(SUM(r.OVERFLOW_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'OVERFLOW', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.WARD_DAILY r JOIN RAW.WARDS s ON s.ID = r.ENTITY_ID
-- Regional bed-board system outages are not ward-driven, so they are excluded from training.
WHERE r.PRESSURE_DRIVER <> 'Bed-board system outage';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.OVERFLOW_TRAIN AS
SELECT CATEGORY, SERVICE_TIER, NURSE_FTE, BOARDING_HOURS, AWAITING_BED, BOARDING_7D, OVERFLOW_30D, LABEL
FROM ML.OVERFLOW_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.OVERFLOW_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, SERVICE_TIER, NURSE_FTE, BOARDING_HOURS, AWAITING_BED, BOARDING_7D, OVERFLOW_30D, LABEL
FROM ML.OVERFLOW_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.OVERFLOW_RISK_MODEL(
  INPUT_DATA => TABLE(ML.OVERFLOW_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.OVERFLOW_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.OVERFLOW_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'SERVICE_TIER', SERVICE_TIER, 'NURSE_FTE', NURSE_FTE,
           'BOARDING_HOURS', BOARDING_HOURS, 'AWAITING_BED', AWAITING_BED,
           'BOARDING_7D', BOARDING_7D, 'OVERFLOW_30D', OVERFLOW_30D)):probability:OVERFLOW::FLOAT AS P
  FROM ML.OVERFLOW_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'OVERFLOW', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'OVERFLOW', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'OVERFLOW', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'OVERFLOW', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per ward (label unknown, so excluded from features).
CREATE TABLE ML.OVERFLOW_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.OVERFLOW_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.OVERFLOW_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'SERVICE_TIER', SERVICE_TIER, 'NURSE_FTE', NURSE_FTE,
           'BOARDING_HOURS', BOARDING_HOURS, 'AWAITING_BED', AWAITING_BED,
           'BOARDING_7D', BOARDING_7D, 'OVERFLOW_30D', OVERFLOW_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:OVERFLOW::FLOAT, 4) AS OVERFLOW_PROB_7D,
       CASE WHEN P:probability:OVERFLOW::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:OVERFLOW::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Group-wide forecast (14 days) of admissions, for bed and nurse capacity planning.
CREATE VIEW ML.DAILY_ADMISSIONS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(ADMISSION_COUNT)::FLOAT AS ADMISSION_COUNT
FROM RAW.WARD_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.ADMISSIONS_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_ADMISSIONS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'ADMISSION_COUNT'
);

CREATE TABLE ML.ADMISSIONS_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS ADMISSION_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.ADMISSIONS_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
