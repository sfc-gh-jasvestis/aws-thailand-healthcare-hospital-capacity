-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ward.ID AS ENTITY_ID, ward.NAME AS ENTITY_NAME,
       ward.REGION, ward.CATEGORY, ward.SERVICE_TIER, ward.STATUS,
       ward.STAFFED_BEDS, ward.PLANNED_ADMISSIONS_90D,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.ADMISSION_COUNT) AS ADMISSION_COUNT,
       SUM(observation.IN_TARGET_COUNT) AS IN_TARGET_COUNT,
       SUM(observation.ESCALATION_COUNT) AS ESCALATION_COUNT,
       SUM(observation.OVERFLOW_COUNT) AS OVERFLOW_COUNT,
       SUM(observation.REVIEW_OPENED) AS REVIEW_COUNT,
       SUM(observation.AUDIT_DUE) AS AUDIT_DUE,
       SUM(observation.AUDIT_COMPLETED) AS AUDIT_COMPLETED,
       SUM(observation.OCCUPIED_BEDS) AS OCCUPIED_BED_DAYS,
       SUM(observation.STAFFED_BEDS) AS STAFFED_BED_DAYS,
       100.0 * SUM(observation.OCCUPIED_BEDS) / NULLIF(SUM(observation.STAFFED_BEDS), 0) AS OCCUPANCY_PCT,
       100.0 * SUM(observation.ADMISSION_COUNT) / NULLIF(ward.PLANNED_ADMISSIONS_90D, 0) AS ADMISSIONS_VS_PLAN_PCT,
       100.0 * (SUM(observation.ADMISSION_COUNT) - SUM(observation.IN_TARGET_COUNT)) / NULLIF(SUM(observation.ADMISSION_COUNT), 0) AS OUTSIDE_TARGET_PCT,
       100.0 * SUM(observation.OVERFLOW_COUNT) / NULLIF(SUM(observation.ESCALATION_COUNT), 0) AS ESCALATION_CONFIRM_PCT,
       100.0 * SUM(observation.AUDIT_COMPLETED) / NULLIF(SUM(observation.AUDIT_DUE), 0) AS AUDIT_COMPLIANCE_PCT,
       AVG(observation.BOARDING_HOURS) AS AVG_BOARDING_HOURS,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.WARD_DAILY observation
JOIN RAW.WARDS ward ON ward.ID = observation.ENTITY_ID
GROUP BY ward.ID, ward.NAME, ward.REGION, ward.CATEGORY, ward.SERVICE_TIER, ward.STATUS,
         ward.STAFFED_BEDS, ward.PLANNED_ADMISSIONS_90D;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(ADMISSION_COUNT) AS ADMISSION_COUNT, SUM(IN_TARGET_COUNT) AS IN_TARGET_COUNT,
       SUM(ESCALATION_COUNT) AS ESCALATION_COUNT, SUM(OVERFLOW_COUNT) AS OVERFLOW_COUNT,
       100.0 * SUM(OCCUPIED_BEDS) / NULLIF(SUM(STAFFED_BEDS), 0) AS OCCUPANCY_PCT,
       100.0 * SUM(OVERFLOW_COUNT) / NULLIF(SUM(ESCALATION_COUNT), 0) AS ESCALATION_CONFIRM_PCT
FROM RAW.WARD_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.DRIVER_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT PRESSURE_DRIVER, SUM(ESCALATION_COUNT) AS ESCALATION_COUNT,
       SUM(OVERFLOW_COUNT) AS OVERFLOW_COUNT,
       SUM(REVIEW_OPENED) AS REVIEW_COUNT,
       COUNT(DISTINCT ENTITY_ID) AS WARDS_AFFECTED,
       100.0 * SUM(OVERFLOW_COUNT) / NULLIF(SUM(ESCALATION_COUNT), 0) AS ESCALATION_CONFIRM_PCT
FROM RAW.WARD_DAILY
WHERE ESCALATION_COUNT > 0
GROUP BY PRESSURE_DRIVER;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(ESCALATION_COUNT) AS SIGNALS, SUM(OVERFLOW_COUNT) AS CONFIRMED,
         SUM(REVIEW_OPENED) AS REVIEWS, SUM(ADMISSION_COUNT) AS ADMITTED, SUM(IN_TARGET_COUNT) AS IN_TARGET,
         SUM(OCCUPIED_BEDS) AS OCCUPIED, SUM(STAFFED_BEDS) AS STAFFED,
         AVG(BOARDING_HOURS) AS AVG_BOARDING, SUM(AWAITING_BED) AS AWAITING_TOTAL,
         SUM(AUDIT_DUE) AS AUDIT_DUE, SUM(AUDIT_COMPLETED) AS AUDIT_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.WARD_DAILY
), portfolio AS (
  SELECT COUNT(*) AS WARD_COUNT, SUM(PLANNED_ADMISSIONS_90D) AS TARGET, SUM(STAFFED_BEDS) AS BEDS
  FROM RAW.WARDS
), fleet AS (
  SELECT 100.0 * SUM(UNITS_CHECKED) / NULLIF(SUM(UNITS_INSTALLED), 0) AS COVERAGE_PCT,
         SUM(CHECKS_PENDING) AS PENDING
  FROM RAW.EQUIPMENT_FLEET
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Admissions vs Plan' AS TITLE,
         100.0 * ADMITTED / NULLIF(TARGET, 0) AS VALUE_NUM, '%' AS UNIT FROM observations CROSS JOIN portfolio
  UNION ALL SELECT 2, 'Admissions', ADMITTED, '' FROM observations
  UNION ALL SELECT 3, 'Bed Occupancy', 100.0 * OCCUPIED / NULLIF(STAFFED, 0), '%' FROM observations
  UNION ALL SELECT 4, 'Admissions Placed Outside Target', 100.0 * (ADMITTED - IN_TARGET) / NULLIF(ADMITTED, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Escalation Confirmation Rate', 100.0 * CONFIRMED / NULLIF(SIGNALS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Bed-Management Escalations', SIGNALS, '' FROM observations
  UNION ALL SELECT 7, 'Confirmed Capacity Overflows', CONFIRMED, '' FROM observations
  UNION ALL SELECT 8, 'Overflow Reviews Opened', REVIEWS, '' FROM observations
  UNION ALL SELECT 9, 'Bed-Flow Audit Compliance', 100.0 * AUDIT_COMPLETED / NULLIF(AUDIT_DUE, 0), '%' FROM observations
  UNION ALL SELECT 10, 'Wards Active', WARD_COUNT, '' FROM portfolio
  UNION ALL SELECT 11, 'Staffed Beds', BEDS, '' FROM portfolio
  UNION ALL SELECT 12, 'Equipment Safety Check Coverage', COVERAGE_PCT, '%' FROM fleet
  UNION ALL SELECT 13, 'Equipment Checks Pending', PENDING, '' FROM fleet
  UNION ALL SELECT 14, 'Average Boarding Time', AVG_BOARDING, ' h' FROM observations
  UNION ALL SELECT 15, 'Awaiting a Bed (ward-day total)', AWAITING_TOTAL, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

